import { describe, expect, it } from 'vitest'
import { buildFirmware } from '@/lib/show/firmware-bundle'
import { compileBenchCues, parseCueTable } from '@/lib/show/bench'
import { clip, project, tableOf, templates, ZONE_IDS } from './helpers/fixtures'

const p = project([clip({ durationMs: 3000 }), clip({ startMs: 3000, effect: 'chase', color: '#00FF00' })], { name: 'Opening $& "act"\n2', lengthMs: 42000 })

describe('buildFirmware (with the real sketches in firmware/)', () => {
  const files = buildFirmware(templates(), p, ZONE_IDS, 0, 'strip', new Date(2026, 9, 30, 14, 5))
  const get = (path: string) => files.find((f) => f.path === path)!.text

  it('produces both sketches, both protocol headers and a README', () => {
    expect(files.map((f) => f.path)).toEqual([
      'base_station/base_station.ino', 'base_station/lumacue_protocol.h',
      'test_costume/test_costume.ino', 'test_costume/lumacue_protocol.h', 'README.txt',
    ])
  })
  it('sets the same show length in both sketches', () => {
    expect(get('base_station/base_station.ino')).toMatch(/const uint32_t SHOW_LENGTH_MS\s*= 42000;/)
    expect(get('test_costume/test_costume.ino')).toMatch(/const uint32_t SHOW_LENGTH_MS\s*= 42000;/)
  })
  it('puts in the show cue table and the LED type', () => {
    const costume = get('test_costume/test_costume.ino')
    expect(costume).toContain('#define OUTPUT_MODE MODE_STRIP')
    const { cues } = compileBenchCues(p, ZONE_IDS, 0)
    expect(parseCueTable(costume)).toEqual(tableOf(cues))
    expect(costume.match(/const Cue SHOW\[\] PROGMEM/g)).toHaveLength(1)
  })
  it("keeps '$' and newlines in a show name from breaking the code", () => {
    const costume = get('test_costume/test_costume.ino')
    expect(costume).toContain('Opening $& "act" 2')
    // every line that mentions the name is a comment
    for (const line of costume.split('\n').filter((l) => l.includes('Opening'))) expect(line.trimStart().startsWith('//')).toBe(true)
  })
  it('stamps the generation date', () => {
    expect(get('base_station/base_station.ino')).toMatch(/^\/\/ Generated by LumaCue on 2026-10-30 14:05/)
  })
  it('writes the strip zone sizes and brightness from Costume Setup', () => {
    const out = buildFirmware(templates(), p, ZONE_IDS, 0, 'strip', new Date(), { zoneLeds: [30, 15, 30, 8], brightnessPct: 40 })
    const costume = out.find((f) => f.path === 'test_costume/test_costume.ino')!.text
    expect(costume).toContain('constexpr uint8_t ZONE_A_LEDS = 30, ZONE_B_LEDS = 15, ZONE_C_LEDS = 30;')
    expect(costume).toMatch(/const uint8_t {2}BRIGHTNESS {5}= 102;/)
    expect(out.find((f) => f.path === 'README.txt')!.text).toContain('zones A/B/C = 30/15/30 LEDs, brightness 102/255')
  })
  it('fails loudly if the sketch template changes shape', () => {
    const t = templates()
    expect(() => buildFirmware({ ...t, costumeIno: t.costumeIno.replaceAll('SHOW_LENGTH_MS', 'SHOW_LEN') }, p, ZONE_IDS, 0, '5mm')).toThrow(/SHOW_LENGTH_MS/)
  })
})
