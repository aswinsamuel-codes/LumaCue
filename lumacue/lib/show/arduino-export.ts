/**
 * Exports one dancer's part of a show as the SHOW[] cue table used by
 * firmware/bench_sync_test/test_costume (3 zones, effects OFF/SOLID/FLASH/CHASE).
 * The cues come from compileBenchCues(), which also drives the bench preview.
 */
import { compileBenchCues, ZALL } from '@/lib/show/bench'
import type { ShowProject } from '@/lib/show/model'

/** One line, safe inside a // comment. */
const oneLine = (text: string) => text.replace(/\s*[\r\n]+\s*/g, ' ')

const zoneText = (mask: number) =>
  mask === ZALL ? 'ZALL' : ['ZA', 'ZB', 'ZC'].filter((_, i) => mask & (1 << i)).join(' | ')

export function exportArduinoShow(project: ShowProject, zoneIds: string[], dancer: number, opts: { pasteInstructions?: boolean } = {}): string {
  const { pasteInstructions = true } = opts
  const { cues, notes } = compileBenchCues(project, zoneIds, dancer)

  const lines = cues.map((c) =>
    `  { ${String(c.startMs).padStart(6)}, ${String(c.durationMs).padStart(5)}, ${zoneText(c.zoneMask)}, ${c.fx}, ${c.r}, ${c.g}, ${c.b}, ${c.param} },  // ${c.source} ${c.effect}`)

  return [
    `// Generated by LumaCue — show "${oneLine(project.name)}", Dancer ${dancer + 1} · ${cues.length} cues`,
    ...(pasteInstructions
      ? [`// Paste over SHOW[] in test_costume.ino, and set:`, `//   const uint32_t SHOW_LENGTH_MS = ${Math.round(project.lengthMs)};   (in base_station.ino too)`]
      : []),
    `// Zones: ZA = ${zoneIds[0] ?? '-'}, ZB = ${zoneIds[1] ?? '-'}, ZC = ${zoneIds[2] ?? '-'}`,
    ...notes.map((n) => `// Note: ${oneLine(n)}`),
    'const Cue SHOW[] PROGMEM = {',
    ...(lines.length ? lines : ['  {      0,  1000, ZALL, FX_OFF, 0, 0, 0, 0 },  // empty show']),
    '};',
  ].join('\n')
}
