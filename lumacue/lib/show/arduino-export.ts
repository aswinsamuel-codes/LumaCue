/**
 * Exports one dancer's part of a show as the SHOW[] cue table used by
 * firmware/bench_sync_test/test_costume (3 zones, effects OFF/SOLID/FLASH/CHASE).
 * Effects the bench firmware can't play are approximated or skipped, with a note.
 */
import { ALL_DANCERS } from '@/lib/show/model'
import type { ShowProject } from '@/lib/show/model'
import { hexToRgb, speedHz } from '@/lib/show/render'

const MAX_DURATION = 65535 // Cue.durationMs is uint16 in the firmware

export function exportArduinoShow(project: ShowProject, zoneIds: string[], dancer: number): string {
  const zoneBits = (ids: string[]) => {
    const names = ['ZA', 'ZB', 'ZC']
    const used = (ids.length ? ids : zoneIds).map((id) => zoneIds.indexOf(id)).filter((i) => i >= 0 && i < 3)
    return used.length === 3 || !used.length ? 'ZALL' : used.map((i) => names[i]).join(' | ')
  }

  const clips = project.clips
    .filter((c) => c.track === ALL_DANCERS || c.track === dancer)
    // Same layering as the simulation: all-costume clips first, the dancer's own on top.
    .sort((a, b) => (a.track === ALL_DANCERS ? 0 : 1) - (b.track === ALL_DANCERS ? 0 : 1) || a.startMs - b.startMs)

  const lines: string[] = []
  const notes = new Set<string>()

  for (const c of clips) {
    let fx: string
    let param = 0
    let [r, g, b] = hexToRgb(c.color)
    switch (c.effect) {
      case 'solid': fx = 'FX_SOLID'; break
      case 'blackout': fx = 'FX_OFF'; r = g = b = 0; break
      case 'strobe': fx = 'FX_FLASH'; param = Math.round(1000 / (speedHz(c.speed) * 2)); break
      case 'pulse': fx = 'FX_FLASH'; param = Math.round(2000 / speedHz(c.speed)); notes.add('Pulse is played as a slow flash (no dimming in bench firmware).'); break
      case 'chase': fx = 'FX_CHASE'; param = Math.round(2000 / speedHz(c.speed)); break
      case 'wipe': fx = 'FX_CHASE'; param = c.durationMs; notes.add('Wipe is played as one chase lap over the clip.'); break
      case 'fade': {
        // No dimming on the bench: hold whichever end of the fade is brighter.
        const c2 = hexToRgb(c.color2)
        if (c2[0] + c2[1] + c2[2] > r + g + b) [r, g, b] = c2
        fx = 'FX_SOLID'
        notes.add('Fade is played as its brighter colour (no dimming in bench firmware).')
        break
      }
      default:
        notes.add(`${c.effect} is not supported by the bench firmware and was skipped.`)
        continue
    }
    for (let start = c.startMs, left = c.durationMs; left > 0; start += MAX_DURATION, left -= MAX_DURATION) {
      const dur = Math.min(left, MAX_DURATION)
      lines.push(`  { ${String(Math.round(start)).padStart(6)}, ${String(Math.round(dur)).padStart(5)}, ${zoneBits(c.zones)}, ${fx}, ${r}, ${g}, ${b}, ${Math.max(0, Math.min(65535, param))} },  // ${c.track === ALL_DANCERS ? 'all' : 'own'} ${c.effect}`)
    }
  }

  return [
    `// Generated by LumaCue — show "${project.name}", Dancer ${dancer + 1}`,
    `// Paste over SHOW[] in test_costume.ino, and set:`,
    `//   const uint32_t SHOW_LENGTH_MS = ${Math.round(project.lengthMs)};   (in base_station.ino too)`,
    `// Zones: ZA = ${zoneIds[0] ?? '-'}, ZB = ${zoneIds[1] ?? '-'}, ZC = ${zoneIds[2] ?? '-'} (only the first 3 costume zones exist on the bench)`,
    ...[...notes].map((n) => `// Note: ${n}`),
    'const Cue SHOW[] PROGMEM = {',
    ...(lines.length ? lines : ['  {      0,  1000, ZALL, FX_OFF, 0, 0, 0, 0 },  // empty show']),
    '};',
  ].join('\n')
}
