/**
 * Builds ready-to-upload bench sketches from the repo templates: the show's
 * cue table goes into test_costume, and the show length into both sketches.
 */
import { exportArduinoShow } from '@/lib/show/arduino-export'
import type { ShowProject } from '@/lib/show/model'

export interface FirmwareTemplates {
  baseIno: string
  baseProtocol: string
  costumeIno: string
  costumeProtocol: string
}

export type LedOutput = '5mm' | 'strip'

const SHOW_TABLE = /const Cue SHOW\[\] PROGMEM = \{[\s\S]*?\n\};/
const SHOW_LENGTH = /const uint32_t SHOW_LENGTH_MS(\s*)=\s*\d+;/
const OUTPUT_MODE = /#define OUTPUT_MODE MODE_\w+/

// Always a function replacer: text like a show name may contain '$', which a
// string replacement would treat as a special pattern.
function replaceOnce(src: string, re: RegExp, value: (...groups: string[]) => string, what: string) {
  if (!re.test(src)) throw new Error(`Couldn't find ${what} in the firmware template. Has the sketch changed?`)
  return src.replace(re, (...m: string[]) => value(...m))
}

export function buildFirmware(
  t: FirmwareTemplates,
  project: ShowProject,
  zoneIds: string[],
  dancer: number,
  output: LedOutput,
  generatedAt = new Date(),
): { path: string; text: string }[] {
  const lengthMs = Math.round(project.lengthMs)
  const pad = (n: number) => String(n).padStart(2, '0')
  const when = `${generatedAt.getFullYear()}-${pad(generatedAt.getMonth() + 1)}-${pad(generatedAt.getDate())} ${pad(generatedAt.getHours())}:${pad(generatedAt.getMinutes())}`
  const stamp = `// Generated by LumaCue on ${when} for show "${project.name.replace(/[\r\n]+/g, ' ')}", Dancer ${dancer + 1}.\n// Edit the show in LumaCue Show Studio and download again rather than editing SHOW[] here.\n\n`
  const len = (src: string) => replaceOnce(src, SHOW_LENGTH, (_, ws) => `const uint32_t SHOW_LENGTH_MS${ws}= ${lengthMs};`, 'SHOW_LENGTH_MS')

  let costume = len(t.costumeIno)
  const table = exportArduinoShow(project, zoneIds, dancer, { pasteInstructions: false })
  costume = replaceOnce(costume, SHOW_TABLE, () => table, 'the SHOW[] cue table')
  costume = replaceOnce(costume, OUTPUT_MODE, () => `#define OUTPUT_MODE ${output === 'strip' ? 'MODE_STRIP' : 'MODE_5MM'}`, 'OUTPUT_MODE')

  const base = len(t.baseIno)

  const readme = [
    `LumaCue firmware for "${project.name}" (Dancer ${dancer + 1})`,
    `Show length: ${(lengthMs / 1000).toFixed(1)} s · LED output: ${output === 'strip' ? 'WS2812B strip (needs the FastLED library)' : '5 mm bi-colour LEDs'}`,
    '',
    '1. Unzip, then open base_station/base_station.ino in the Arduino IDE and upload it to the base Nano.',
    '2. Open test_costume/test_costume.ino and upload it to the costume Nano.',
    '3. Close the Arduino Serial Monitor, then in LumaCue Show Mode click CONNECT USB, ARM, START.',
    '',
    'Board: Arduino Nano · Processor: ATmega328P (Old Bootloader) · Libraries: RF24' + (output === 'strip' ? ', FastLED' : ''),
    'Wiring and the full test plan: firmware/bench_sync_test/README.md in the LumaCue repo.',
    '',
  ].join('\r\n')

  return [
    { path: 'base_station/base_station.ino', text: stamp + base },
    { path: 'base_station/lumacue_protocol.h', text: t.baseProtocol },
    { path: 'test_costume/test_costume.ino', text: stamp + costume },
    { path: 'test_costume/lumacue_protocol.h', text: t.costumeProtocol },
    { path: 'README.txt', text: readme },
  ]
}
