/**
 * Builds ready-to-upload bench sketches from the repo templates: the show's
 * cue table goes into test_costume, and the show length into both sketches.
 */
import { exportArduinoShow } from '@/lib/show/arduino-export'
import type { ShowProject } from '@/lib/show/model'
import { benchPositions, benchZoneLeds } from '@/lib/show/bench'
import type { ZoneShape } from '@/lib/show/body'

export interface FirmwareTemplates {
  baseIno: string
  baseProtocol: string
  costumeIno: string
  costumeProtocol: string
}

export type LedOutput = '5mm' | 'strip'

/** Which controller the sketches are for. ESP32 drives a WS2812B strip over ESP-NOW. */
export type Board = 'nano' | 'esp32'

const BOARD_INFO: Record<Board, { base: string; costume: string; boardText: string; docs: string }> = {
  nano: { base: 'base_station', costume: 'test_costume', boardText: 'Board: Arduino Nano · Processor: ATmega328P (Old Bootloader)', docs: 'firmware/bench_sync_test/README.md' },
  esp32: { base: 'base', costume: 'costume', boardText: 'Board: ESP32 Dev Module (arduino-esp32 core)', docs: 'firmware/esp32/README.md' },
}

const SHOW_TABLE = /const Cue SHOW\[\] PROGMEM = \{[\s\S]*?\n\};/
const SHOW_LENGTH = /const uint32_t SHOW_LENGTH_MS(\s*)=\s*\d+;/
const OUTPUT_MODE = /#define OUTPUT_MODE MODE_\w+/
const ZONE_SIZES = /constexpr uint8_t ZONE_A_LEDS = \d+, ZONE_B_LEDS = \d+, ZONE_C_LEDS = \d+;/
const BRIGHTNESS = /const uint8_t  BRIGHTNESS     = \d+;/
// LED positions for the canvas effects, between marker comments (kept so the sketch can be filled again).
const PIX_POS_STRIP = /([ \t]*)\/\/ PIX_POS strip begin\r?\n[\s\S]*?\/\/ PIX_POS strip end/
const PIX_POS_5MM = /([ \t]*)\/\/ PIX_POS 5mm begin\r?\n[\s\S]*?\/\/ PIX_POS 5mm end/

/** The PIX_POS table (x, y per pixel) as C, between its marker comments. */
export function pixPosBlock(pos: Uint8Array, indent: string, which: 'strip' | '5mm'): string {
  const pairs: string[] = []
  for (let i = 0; i < pos.length / 2; i++) pairs.push(`{${pos[i * 2]}, ${pos[i * 2 + 1]}}`)
  const rows: string[] = []
  for (let i = 0; i < pairs.length; i += 8) rows.push(`${indent}  ${pairs.slice(i, i + 8).join(', ')},`)
  return [
    `${indent}// PIX_POS ${which} begin`,
    `${indent}const uint8_t PIX_POS[NUM_PIXELS][2] PROGMEM = {`,
    ...rows,
    `${indent}};`,
    `${indent}// PIX_POS ${which} end`,
  ].join('\n')
}

/**
 * Writes the LED position tables into a costume sketch: the strip table (both
 * boards) and, in the bench sketch, the 5 mm table.
 */
export function fillPixPos(src: string, zones: ZoneShape[]) {
  let out = replaceOnce(src, PIX_POS_STRIP, (_, indent) => pixPosBlock(benchPositions('strip', zones), indent, 'strip'), 'the PIX_POS strip markers')
  if (PIX_POS_5MM.test(out)) out = out.replace(PIX_POS_5MM, (_, indent) => pixPosBlock(benchPositions('5mm', zones), indent, '5mm'))
  return out
}

/** Strip settings taken from Costume Setup. */
export interface StripSettings {
  zoneLeds: number[]     // LEDs per zone, in strip order (first 3 are used)
  brightnessPct: number  // brightness cap, 5–100 %
  shapes?: ZoneShape[]   // where each zone sits on the body: preset or drawn lines (LED positions for the canvas effects)
}

// Always a function replacer: text like a show name may contain '$', which a
// string replacement would treat as a special pattern.
function replaceOnce(src: string, re: RegExp, value: (...groups: string[]) => string, what: string) {
  if (!re.test(src)) throw new Error(`Couldn't find ${what} in the firmware template. Has the sketch changed?`)
  return src.replace(re, (...m: string[]) => value(...m))
}

export function buildFirmware(
  t: FirmwareTemplates,
  project: ShowProject,
  zoneIds: string[],
  dancer: number,
  output: LedOutput,
  generatedAt = new Date(),
  strip: StripSettings = { zoneLeds: [20, 20, 20], brightnessPct: 25 },
  board: Board = 'nano',
): { path: string; text: string }[] {
  if (board === 'esp32') output = 'strip' // the ESP32 costume drives a strip only
  const info = BOARD_INFO[board]
  const lengthMs = Math.round(project.lengthMs)
  const pad = (n: number) => String(n).padStart(2, '0')
  const when = `${generatedAt.getFullYear()}-${pad(generatedAt.getMonth() + 1)}-${pad(generatedAt.getDate())} ${pad(generatedAt.getHours())}:${pad(generatedAt.getMinutes())}`
  const stamp = `// Generated by LumaCue on ${when} for show "${project.name.replace(/[\r\n]+/g, ' ')}", Dancer ${dancer + 1}.\n// Edit the show in LumaCue Show Studio and download again rather than editing SHOW[] here.\n\n`
  const len = (src: string) => replaceOnce(src, SHOW_LENGTH, (_, ws) => `const uint32_t SHOW_LENGTH_MS${ws}= ${lengthMs};`, 'SHOW_LENGTH_MS')

  let costume = len(t.costumeIno)
  const table = exportArduinoShow(project, zoneIds, dancer, { pasteInstructions: false, output })
  costume = replaceOnce(costume, SHOW_TABLE, () => table, 'the SHOW[] cue table')
  costume = replaceOnce(costume, OUTPUT_MODE, () => `#define OUTPUT_MODE ${output === 'strip' ? 'MODE_STRIP' : 'MODE_5MM'}`, 'OUTPUT_MODE')
  const [a, b, c] = benchZoneLeds(strip.zoneLeds)
  costume = replaceOnce(costume, ZONE_SIZES, () => `constexpr uint8_t ZONE_A_LEDS = ${a}, ZONE_B_LEDS = ${b}, ZONE_C_LEDS = ${c};`, 'the ZONE_x_LEDS sizes')
  const level = Math.max(1, Math.min(255, Math.round((Math.max(0, Math.min(100, strip.brightnessPct)) * 255) / 100)))
  costume = replaceOnce(costume, BRIGHTNESS, () => `const uint8_t  BRIGHTNESS     = ${level};`, 'BRIGHTNESS')
  const defaultShapes: ZoneShape[] = [{ leds: 20, placement: 'arms' }, { leds: 20, placement: 'chest' }, { leds: 20, placement: 'legs' }]
  costume = fillPixPos(costume, [0, 1, 2].map((i) => ({ ...(strip.shapes?.[i] ?? defaultShapes[i]), leds: strip.zoneLeds[i] ?? 0 })))

  const base = len(t.baseIno)

  const readme = [
    `LumaCue firmware for "${project.name}" (Dancer ${dancer + 1})`,
    `Show length: ${(lengthMs / 1000).toFixed(1)} s · LED output: ${output === 'strip' ? `WS2812B strip (needs the FastLED library): zones A/B/C = ${a}/${b}/${c} LEDs, brightness ${level}/255` : '5 mm bi-colour LEDs'}`,
    '',
    `1. Unzip, then open ${info.base}/${info.base}.ino in the Arduino IDE and upload it to the base station.`,
    `2. Open ${info.costume}/${info.costume}.ino and upload it to the costume.`,
    '3. Close the Arduino Serial Monitor, then in LumaCue Show Mode click CONNECT USB, ARM, START.',
    '',
    `${info.boardText} · Libraries: ${board === 'esp32' ? 'FastLED' : 'RF24' + (output === 'strip' ? ', FastLED' : '')}`,
    `Wiring and tests: ${info.docs} in the LumaCue repo.`,
    '',
  ].join('\r\n')

  return [
    { path: `${info.base}/${info.base}.ino`, text: stamp + base },
    { path: `${info.base}/lumacue_protocol.h`, text: t.baseProtocol },
    { path: `${info.costume}/${info.costume}.ino`, text: stamp + costume },
    { path: `${info.costume}/lumacue_protocol.h`, text: t.costumeProtocol },
    { path: 'README.txt', text: readme },
  ]
}

/**
 * Every dancer at once: the base station sketch once, then one costume sketch
 * per dancer in dancer_01/ … (each folder still opens as an Arduino sketch).
 */
export function buildFirmwareForAll(
  t: FirmwareTemplates,
  project: ShowProject,
  zoneIds: string[],
  output: LedOutput,
  generatedAt = new Date(),
  strip?: StripSettings,
  board: Board = 'nano',
): { path: string; text: string }[] {
  const info = BOARD_INFO[board]
  const files: { path: string; text: string }[] = []
  const pad = String(project.dancers).length < 2 ? 2 : String(project.dancers).length
  for (let d = 0; d < project.dancers; d++) {
    const one = buildFirmware(t, project, zoneIds, d, output, generatedAt, strip, board)
    if (d === 0) files.push(...one.filter((f) => f.path.startsWith(`${info.base}/`)))
    const dir = `dancer_${String(d + 1).padStart(pad, '0')}`
    files.push(...one.filter((f) => f.path.startsWith(`${info.costume}/`)).map((f) => ({ path: `${dir}/${f.path}`, text: f.text })))
  }
  const readme = [
    `LumaCue firmware for "${project.name.replace(/[\r\n]+/g, ' ')}": all ${project.dancers} dancers`,
    `Show length: ${(Math.round(project.lengthMs) / 1000).toFixed(1)} s · LED output: ${board === 'esp32' || output === 'strip' ? 'WS2812B strip (needs the FastLED library)' : '5 mm bi-colour LEDs'}`,
    '',
    `1. Upload ${info.base}/${info.base}.ino to the base station (once).`,
    `2. For each dancer, upload dancer_NN/${info.costume}/${info.costume}.ino to that dancer's costume. Label the boards!`,
    '3. Close the Arduino Serial Monitor, then in LumaCue Show Mode click CONNECT USB, ARM, START.',
    '',
    `${info.boardText} · Libraries: ${board === 'esp32' ? 'FastLED' : 'RF24' + (output === 'strip' ? ', FastLED' : '')}`,
    '',
  ].join('\r\n')
  files.push({ path: 'README.txt', text: readme })
  return files
}
